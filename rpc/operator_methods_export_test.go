package rpc

import (
	"bytes"
	"os"
	"path/filepath"
	"sort"
	"strings"
	"testing"
)

// The node's operator-only method table is kept in step by hand with the table in
// the browser-facing gateway, which lives in another repository (PL-DC-51). This
// test makes the node's side checkable by a machine: it writes the table, sorted,
// to rpc/testdata/operator_only_methods.txt, and fails when the table in code and
// the file differ. The other side compares its own list with this file (one name per
// line, a trailing "*" marks a prefix), so a change to either table is a visible
// diff in a review, not a silent drift.
//
// Regenerate after a deliberate change to OperatorOnlyMethods or
// OperatorOnlyMethodPrefixes:
//
//	NHB_UPDATE_OPERATOR_TABLE=1 go test ./rpc -run TestOperatorOnlyTableMatchesTheExportedFile
const operatorTableFile = "testdata/operator_only_methods.txt"

func renderOperatorTable() []byte {
	names := make([]string, 0, len(OperatorOnlyMethods)+len(OperatorOnlyMethodPrefixes))
	for name := range OperatorOnlyMethods {
		names = append(names, name)
	}
	for _, prefix := range OperatorOnlyMethodPrefixes {
		names = append(names, prefix+"*")
	}
	sort.Strings(names)
	var b bytes.Buffer
	b.WriteString("# Operator-only RPC methods of this node (rpc/operator_methods.go), sorted.\n")
	b.WriteString("# A trailing * is a prefix. Generated by TestOperatorOnlyTableMatchesTheExportedFile; do not edit.\n")
	for _, n := range names {
		b.WriteString(n)
		b.WriteByte('\n')
	}
	return b.Bytes()
}

func TestOperatorOnlyTableMatchesTheExportedFile(t *testing.T) {
	want := renderOperatorTable()
	path := filepath.FromSlash(operatorTableFile)
	if os.Getenv("NHB_UPDATE_OPERATOR_TABLE") == "1" {
		if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(path, want, 0o644); err != nil {
			t.Fatal(err)
		}
		t.Logf("wrote %s", path)
		return
	}
	got, err := os.ReadFile(path)
	if err != nil {
		t.Fatalf("read %s: %v (regenerate with NHB_UPDATE_OPERATOR_TABLE=1)", path, err)
	}
	if !bytes.Equal(bytes.ReplaceAll(got, []byte("\r\n"), []byte("\n")), want) {
		t.Fatalf("the operator-only table in code differs from rpc/%s: regenerate it with NHB_UPDATE_OPERATOR_TABLE=1 and make the same change in the gateway's list in the same release", operatorTableFile)
	}
}

// Every name in the file is something IsOperatorOnlyMethod really refuses, so the
// file cannot hold a name the code would let through.
func TestEveryExportedOperatorOnlyNameIsRefusedByTheGate(t *testing.T) {
	for _, line := range strings.Split(string(renderOperatorTable()), "\n") {
		line = strings.TrimSpace(line)
		if line == "" || strings.HasPrefix(line, "#") {
			continue
		}
		probe := line
		if strings.HasSuffix(probe, "*") {
			probe = strings.TrimSuffix(probe, "*") + "zz_probe"
		}
		if !IsOperatorOnlyMethod(probe) {
			t.Errorf("%q is exported as operator-only but the gate lets it through", probe)
		}
	}
}
